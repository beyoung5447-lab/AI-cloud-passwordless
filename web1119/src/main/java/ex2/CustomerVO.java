package ex2;

public class CustomerVO {
	private int num;
	private String name;
	private String email;
	private String phone;
	private String cadte;

	public int getNum() {
		return num;
	}

	public void setNum(int num) {
		this.num = num;
	}

	public String getName() {
		return name;
	}

	public void setName(String name) {
		this.name = name;
	}

	public String getEmail() {
		return email;
	}

	public void setEmail(String email) {
		this.email = email;
	}

	public String getPhone() {
		return phone;
	}

	public void setPhone(String phone) {
		this.phone = phone;
	}

	public String getCadte() {
		return cadte;
	}

	public void setCadte(String cadte) {
		this.cadte = cadte;
	}

}
