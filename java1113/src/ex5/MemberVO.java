package ex5;

public class MemberVO {
private int num;
private String id;
private boolean agree;
private int age;
public int getAge() {
	return age;
}
public void setAge(int age) {
	this.age = age;
}
public int getNum() {
	return num;
}
public void setNum(int num) {
	this.num = num;
}
public String getId() {
	return id;
}
public void setId(String id) {
	this.id = id;
}
public boolean isAgree() {
	return agree;
}
public void setAgree(boolean agree) {
	this.agree = agree;
}
}
